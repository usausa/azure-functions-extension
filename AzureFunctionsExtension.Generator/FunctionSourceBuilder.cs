    // クラス全体で共有する静的フィールド (target/provider/serializer/filter など) を含む
    // __shared__ ファイルを生成する。
    // Generates the __shared__ file containing static fields shared across all handlers
    // (target instance, service provider, serializer, validator, filters).
    public static void BuildShared(SourceBuilder builder, FunctionModel model)
    {
        builder.AutoGenerated();
        builder.EnableNullable();
        builder.Disable("CS0612, CS0618");
        builder.NewLine();

        if (!String.IsNullOrEmpty(model.Namespace))
        {
            builder.Namespace(model.Namespace);
            builder.NewLine();
        }

        var classKeyword = model.IsValueType ? "struct" : "class";
        builder.AppendLine($"partial {classKeyword} {CSharpIdentifier.EscapeTypeName(model.ClassName)}");
        builder.BeginScope();
        if (model.Handlers.Any(static x => x.Type == HandlerType.Http))
        {
            // 読み取りと検証の失敗の応答を作る。部品は失敗したときだけ呼び出しのスコープから取り出し、登録がなければ文字列の 400 にする
            // Creates the response for a binding or validation failure. The factory is resolved from the invocation scope only on failure, and a text 400 is used without the registration
            builder.AppendLine($"private static {IActionResultType} __BindingErrorResult__(global::System.IServiceProvider services, {BindingErrorType} error, string message) =>");
            builder.AppendLine($"    {GetService}<{BindingErrorResultFactoryType}>(services)?.Create(error) ?? new {BadRequestResultType}(message);");
        }

        builder.EndScope();
    }

    // 1 ハンドラーに対応する部分クラスファイルを生成する。
    // フィルターが存在する場合は InnerMethod + Pipeline を先に出力し、
    // その後にエントリーポイントとなる HandlerMethod を出力する。
    // Generates a partial class file for one handler.
    // When filters exist, emits InnerMethod + Pipeline before the entry-point HandlerMethod.
    public static void Build(SourceBuilder builder, FunctionModel model, HandlerModel handler)
    {
        builder.AutoGenerated();
        builder.EnableNullable();
        builder.Disable("CS0612, CS0618");
        builder.NewLine();

        if (!String.IsNullOrEmpty(model.Namespace))
        {
            builder.Namespace(model.Namespace);
            builder.NewLine();
        }

        var classKeyword = model.IsValueType ? "struct" : "class";
        builder.AppendLine($"partial {classKeyword} {CSharpIdentifier.EscapeTypeName(model.ClassName)}");
        builder.BeginScope();

        if (model.Filters.Count > 0)
        {
            // フィルターがある場合：InnerMethod (実処理) とパイプラインを生成してから HandlerMethod を出力する
            // With filters: emit InnerMethod (actual logic) and pipeline, then the HandlerMethod entry point
            BuildInnerMethod(builder, model, handler);
            builder.NewLine();
            BuildPipeline(builder, model, handler);
            builder.NewLine();
        }

        BuildHandlerMethod(builder, model, handler);

        builder.EndScope();
    }

    // フィルターパイプラインから呼ばれる Inner メソッドを生成する。
    // FunctionInvocationContext 経由でリクエストを受け取り、パラメータバインドと実メソッド呼び出しを行う。
    // Generates the inner method called by the filter pipeline.
    // Receives the request via FunctionInvocationContext, binds parameters, and invokes the actual handler.
    private static void BuildInnerMethod(SourceBuilder builder, FunctionModel model, HandlerModel handler)
    {
        builder.AppendLine($"private static async global::System.Threading.Tasks.ValueTask __{handler.MethodName}_Inner__(");
        builder.AppendLine($"    {InvocationContextType} ctx,");
        builder.AppendLine("    global::System.IServiceProvider services,");
        builder.AppendLine($"    {model.FunctionType.FullName} target)");
        builder.BeginScope();

        if (handler.Type == HandlerType.Http)
        {
            // ctx.Request を HttpRequest にキャストして req 変数として取り出す
            // Cast ctx.Request to HttpRequest and expose it as req
            builder.AppendLine($"var req = ({HttpRequestType})ctx.Request!;");
            builder.NewLine();
        }
        else if (handler.Type == HandlerType.Timer)
        {
            builder.AppendLine($"var timerInfo = ({TimerInfoType})ctx.Request!;");
            builder.NewLine();
        }
        else if (handler.Type == HandlerType.Queue)
        {
            builder.AppendLine("var message = (string)ctx.Request!;");
            builder.NewLine();
        }

        BuildParameterBindings(builder, handler, hasFilter: true);
        BuildHandlerInvocation(builder, handler, hasFilter: true);

        builder.EndScope();
    }

    // フィルターを逆順に合成してミドルウェアパイプラインを構築する静的フィールドとファクトリメソッドを生成する。
    // InnerMethod を末端として、外側のフィルターから順に包み込む形で delegate チェーンを作る。
    // Generates a static pipeline field and factory method that compose filters in reverse order,
    // wrapping the InnerMethod as the terminal delegate to form a middleware chain.
    private static void BuildPipeline(SourceBuilder builder, FunctionModel model, HandlerModel handler)
    {
        var pascal = ToPascalCase(handler.MethodName);
        builder.AppendLine($"private static {FilterDelegateType} Build{pascal}Pipeline(");
        builder.AppendLine("    global::System.IServiceProvider services,");
        builder.AppendLine($"    {model.FunctionType.FullName} target)");
        builder.BeginScope();

        var filters = model.Filters;
        // Inner メソッドをパイプラインの末端 (terminal) として設定する
        // Set the inner method as the terminal of the pipeline
        builder.AppendLine($"{FilterDelegateType} p = ctx => __{handler.MethodName}_Inner__(ctx, services, target);");
        builder.NewLine();

        // 末尾のフィルターから先頭に向かって順に delegate を包み込む (onion model)
        // Wrap delegates from the last filter toward the first (onion model)
        for (var i = filters.Count - 1; i >= 0; i--)
        {
            var filterType = filters[i].FullName;
            builder.AppendLine($"var inner{i} = p;");
            builder.AppendLine($"var filter{i} = {GetService}<{filterType}>(services) ??");
            builder.AppendLine($"    {ActivatorUtilitiesType}.CreateInstance<{filterType}>(services);");
            builder.AppendLine($"p = ctx => filter{i}.InvokeAsync(ctx, inner{i});");
            if (i > 0)
            {
                builder.NewLine();
            }
        }

        builder.NewLine();
        builder.AppendLine("return p;");
        builder.EndScope();
    }

    // [Function] 属性を付与したエントリーポイントメソッドをハンドラーの種類に応じて振り分けて生成する。
    // Generates the [Function]-attributed entry-point method, dispatching to the appropriate builder
    // based on handler kind (Http / Timer / Queue).
    private static void BuildHandlerMethod(SourceBuilder builder, FunctionModel model, HandlerModel handler)
    {
        builder.AppendLine($"[{FunctionAttributeType}({CSharpLiteral.Format(handler.MethodName)})]");

        switch (handler.Type)
        {
            case HandlerType.Http:
                BuildHttpHandlerMethod(builder, model, handler, model.Filters.Count > 0);
                break;
            case HandlerType.Timer:
                BuildTimerHandlerMethod(builder, model, handler, model.Filters.Count > 0);
                break;
            case HandlerType.Queue:
                BuildQueueHandlerMethod(builder, model, handler, model.Filters.Count > 0);
                break;
        }
    }

    // HTTP トリガー向けエントリーポイントを生成する。
    // フィルターあり: InvocationContext を作成してパイプラインに委譲し、ApiException / Exception を補足して適切な IActionResult を返す。
    // フィルターなし: 直接パラメータバインドと呼び出しを行い、例外をハンドリングする。
    // Generates an HTTP trigger entry-point.
    // With filters: creates InvocationContext, delegates to the pipeline, and catches ApiException/Exception.
    // Without filters: binds parameters and invokes directly with exception handling.
    private static void BuildHttpHandlerMethod(SourceBuilder builder, FunctionModel model, HandlerModel handler, bool hasFilters)
    {
        var authLevel = $"global::Microsoft.Azure.Functions.Worker.AuthorizationLevel.{handler.GetAuthorizationLevel()}";
        var httpMethod = handler.GetHttpMethod();
        var route = handler.GetRoute();

        builder.AppendLine($"public static async global::System.Threading.Tasks.Task<{IActionResultType}> {handler.GetEntryPointMethodName()}(");
        builder.AppendLine($"    [{HttpTriggerType}({authLevel}, {CSharpLiteral.Format(httpMethod)}, Route = {CSharpLiteral.Format(route)})] {HttpRequestType} req,");
        builder.AppendLine($"    {FunctionContextType} context)");
        builder.BeginScope();

        BuildInvocationSetup(builder, model, handler);
        builder.NewLine();

        if (hasFilters)
        {
            builder.AppendLine($"var ctx = new {InvocationContextType}");
            builder.BeginScope();
            builder.AppendLine("Request = req,");
            builder.AppendLine("FunctionContext = context,");
            builder.AppendLine($"CancellationToken = {InvocationCancellationToken},");
            builder.EndScope(semicolon: true);
            builder.AppendLine($"var pipeline = Build{ToPascalCase(handler.MethodName)}Pipeline(services, target);");
            builder.NewLine();

            builder.AppendLine("try");
            builder.BeginScope();
            builder.AppendLine("await pipeline(ctx);");
            builder.EndScope();
            builder.AppendLine($"catch ({ApiExceptionType} ex)");
            builder.BeginScope();
            builder.AppendLine($"return new {ObjectResultType}(ex.Message) {{ StatusCode = ex.StatusCode }};");
            builder.EndScope();
            builder.AppendLine("catch (global::System.Exception ex)");
            builder.BeginScope();
            builder.AppendLine($"{LogErrorMethod}({GetLoggerMethod}(context, context.FunctionDefinition.Name), ex, ex.Message);");
            builder.AppendLine($"return new {StatusCodeResultType}(500);");
            builder.EndScope();
            builder.NewLine();
            builder.AppendLine($"return ({IActionResultType})ctx.Result!;");
        }
        else
        {
            builder.AppendLine("try");
            builder.BeginScope();
            BuildParameterBindings(builder, handler, hasFilter: false);
            BuildHandlerInvocation(builder, handler, hasFilter: false);
            builder.EndScope();
            builder.AppendLine($"catch ({ApiExceptionType} ex)");
            builder.BeginScope();
            builder.AppendLine($"return new {ObjectResultType}(ex.Message) {{ StatusCode = ex.StatusCode }};");
            builder.EndScope();
            builder.AppendLine("catch (global::System.Exception ex)");
            builder.BeginScope();
            builder.AppendLine($"{LogErrorMethod}({GetLoggerMethod}(context, context.FunctionDefinition.Name), ex, ex.Message);");
            builder.AppendLine($"return new {StatusCodeResultType}(500);");
            builder.EndScope();
        }

        builder.EndScope();
    }

    // タイマートリガー向けエントリーポイントを生成する。
    // フィルターあり: InvocationContext 経由でパイプラインに委譲。
    // フィルターなし: FromServices パラメータを解決して直接呼び出す。
    // Generates a Timer trigger entry-point.
    // With filters: delegates to the pipeline via InvocationContext.
    // Without filters: resolves FromServices parameters and invokes directly.
    private static void BuildTimerHandlerMethod(SourceBuilder builder, FunctionModel model, HandlerModel handler, bool hasFilters)
    {
        var schedule = handler.GetTimerSchedule();

        builder.AppendLine($"public static async global::System.Threading.Tasks.Task {handler.GetEntryPointMethodName()}(");
        builder.AppendLine($"    [{TimerTriggerType}({CSharpLiteral.Format(schedule)})] {TimerInfoType} timerInfo,");
        builder.AppendLine($"    {FunctionContextType} context)");
        builder.BeginScope();

        BuildInvocationSetup(builder, model, handler);
        builder.NewLine();

        if (hasFilters)
        {
            builder.AppendLine($"var ctx = new {InvocationContextType}");
            builder.BeginScope();
            builder.AppendLine("Request = timerInfo,");
            builder.AppendLine("FunctionContext = context,");
            builder.AppendLine($"CancellationToken = {InvocationCancellationToken},");
            builder.EndScope(semicolon: true);
            builder.AppendLine($"var pipeline = Build{ToPascalCase(handler.MethodName)}Pipeline(services, target);");
            builder.NewLine();
            builder.AppendLine("try");
            builder.BeginScope();
            builder.AppendLine("await pipeline(ctx);");
            builder.EndScope();
            builder.AppendLine("catch (global::System.Exception ex)");
            builder.BeginScope();
            builder.AppendLine($"{LogErrorMethod}({GetLoggerMethod}(context, context.FunctionDefinition.Name), ex, ex.Message);");
            builder.AppendLine("throw;");
            builder.EndScope();
        }
        else
        {
            builder.AppendLine("try");
            builder.BeginScope();
            BuildTimerParameterBindings(builder, handler);
            BuildHandlerInvocation(builder, handler, hasFilter: false);
            builder.EndScope();
            builder.AppendLine("catch (global::System.Exception ex)");
            builder.BeginScope();
            builder.AppendLine($"{LogErrorMethod}({GetLoggerMethod}(context, context.FunctionDefinition.Name), ex, ex.Message);");
            builder.AppendLine("throw;");
            builder.EndScope();
        }

        builder.EndScope();
    }

    // キュートリガー向けエントリーポイントを生成する。
    // フィルターあり: InvocationContext 経由でパイプラインに委譲。
    // フィルターなし: FromServices パラメータを解決して直接呼び出す。
    // Generates a Queue trigger entry-point.
    // With filters: delegates to the pipeline via InvocationContext.
    // Without filters: resolves FromServices parameters and invokes directly.
    private static void BuildQueueHandlerMethod(SourceBuilder builder, FunctionModel model, HandlerModel handler, bool hasFilters)
    {
        var queueName = handler.GetQueueName();
        var connectionPart = handler.QueueConnection is not null ? $", Connection = {CSharpLiteral.Format(handler.QueueConnection)}" : string.Empty;

        builder.AppendLine($"public static async global::System.Threading.Tasks.Task {handler.GetEntryPointMethodName()}(");
        builder.AppendLine($"    [{QueueTriggerType}({CSharpLiteral.Format(queueName)}{connectionPart})] string message,");
        builder.AppendLine($"    {FunctionContextType} context)");
        builder.BeginScope();

        BuildInvocationSetup(builder, model, handler);
        builder.NewLine();

        if (hasFilters)
        {
            builder.AppendLine($"var ctx = new {InvocationContextType}");
            builder.BeginScope();
            builder.AppendLine("Request = message,");
            builder.AppendLine("FunctionContext = context,");
            builder.AppendLine($"CancellationToken = {InvocationCancellationToken},");
            builder.EndScope(semicolon: true);
            builder.AppendLine($"var pipeline = Build{ToPascalCase(handler.MethodName)}Pipeline(services, target);");
            builder.NewLine();
            builder.AppendLine("try");
            builder.BeginScope();
            builder.AppendLine("await pipeline(ctx);");
            builder.EndScope();
            builder.AppendLine("catch (global::System.Exception ex)");
            builder.BeginScope();
            builder.AppendLine($"{LogErrorMethod}({GetLoggerMethod}(context, context.FunctionDefinition.Name), ex, ex.Message);");
            builder.AppendLine("throw;");
            builder.EndScope();
        }
        else
        {
            builder.AppendLine("try");
            builder.BeginScope();
            BuildQueueParameterBindings(builder, handler);
            BuildHandlerInvocation(builder, handler, hasFilter: false);
            builder.EndScope();
            builder.AppendLine("catch (global::System.Exception ex)");
            builder.BeginScope();
            builder.AppendLine($"{LogErrorMethod}({GetLoggerMethod}(context, context.FunctionDefinition.Name), ex, ex.Message);");
            builder.AppendLine("throw;");
            builder.EndScope();
        }

        builder.EndScope();
    }

    // HTTP ハンドラーの全パラメータに対してバインディングコードを順に出力する。
    // Emits binding code for all parameters of an HTTP handler in order.
    private static void BuildParameterBindings(SourceBuilder builder, HandlerModel handler, bool hasFilter)
    {
        var cancellationToken = hasFilter
            ? "ctx.CancellationToken"
            : HasCancellationTokenParameter(handler) ? InvocationCancellationToken : "context.CancellationToken";
        var parameters = handler.Parameters;
        for (var i = 0; i < parameters.Count; i++)
        {
            BuildParameterBinding(builder, parameters[i], i, hasFilter, cancellationToken);
        }
    }

    // タイマーハンドラーで FromServices パラメータのみ DI から解決するコードを出力する。
    // Emits DI resolution code only for FromServices parameters in a Timer handler.
    private static void BuildTimerParameterBindings(SourceBuilder builder, HandlerModel handler)
    {
        var parameters = handler.Parameters;
        for (var i = 0; i < parameters.Count; i++)
        {
            var p = parameters[i];
            if (p.BindingType == ParameterBindingType.FromServices)
            {
                builder.AppendLine($"var p{i} = {ResolveServiceExpression(p.Type.FullName, p.Key)};");
                builder.NewLine();
            }
        }
    }

    // [FromServices] のキー指定有無に応じて非キー付き／キー付き DI 解決式を生成する。
    // Builds a non-keyed or keyed DI resolution expression depending on the [FromServices] key.
    private static string ResolveServiceExpression(string typeName, string key) =>
        String.IsNullOrEmpty(key)
            ? $"{GetRequiredService}<{typeName}>(services)"
            : $"{GetRequiredKeyedService}<{typeName}>(services, {CSharpLiteral.Format(key)})";

    // キューハンドラーで FromServices パラメータのみ DI から解決するコードを出力する。
    // Emits DI resolution code only for FromServices parameters in a Queue handler.
    private static void BuildQueueParameterBindings(SourceBuilder builder, HandlerModel handler)
    {
        var parameters = handler.Parameters;
        for (var i = 0; i < parameters.Count; i++)
        {
            var p = parameters[i];
            if (p.BindingType == ParameterBindingType.FromServices)
            {
                builder.AppendLine($"var p{i} = {ResolveServiceExpression(p.Type.FullName, p.Key)};");
                builder.NewLine();
            }
        }
    }

    // 1 つのパラメータについてバインディング種別に応じたコードを出力する。
    // HttpRequest / FunctionContext / CancellationToken / Logger は呼び出し時に直接渡すためスキップ。
    // FromServices は DI 解決、FromBody はデシリアライズ＋バリデーション、
    // FromQuery / FromRoute / FromHeader は文字列変換を経由して代入する。
    // Emits binding code for a single parameter based on its binding kind.
    // HttpRequest / FunctionContext / CancellationToken / Logger are passed directly at call site, so skipped here.
    // FromServices: DI resolution. FromBody: deserialize + validate.
    // FromQuery / FromRoute / FromHeader: string conversion then assignment.
    private static void BuildParameterBinding(SourceBuilder builder, ParameterModel param, int index, bool hasFilter, string cancellationToken)
    {
        var pVar = $"p{index}";
        var typeName = param.Type.FullName;

        switch (param.BindingType)
        {
            case ParameterBindingType.HttpRequest:
            case ParameterBindingType.Context:
            case ParameterBindingType.CancellationToken:
            case ParameterBindingType.Logger:
            case ParameterBindingType.User:
                return;
            case ParameterBindingType.FromServices:
                builder.AppendLine($"var {pVar} = {ResolveServiceExpression(typeName, param.Key)};");
                builder.NewLine();
                return;
            case ParameterBindingType.FromBody:
                builder.AppendLine($"var bodySerializer{index} = {GetService}<{BodySerializerType}>(services) ?? {DefaultBodySerializerType}.Default;");
                builder.AppendLine($"var {pVar} = default({typeName})!;");
                builder.AppendLine("try");
                builder.BeginScope();
                builder.AppendLine($"{pVar} = await bodySerializer{index}.DeserializeAsync<{typeName}>(req.Body, {cancellationToken});");
                builder.EndScope();
                builder.AppendLine($"catch ({JsonExceptionType})");
                builder.BeginScope();
                AppendBindingFailure(builder, hasFilter, NewBindingError("InvalidBody", "Body", param.Name), CSharpLiteral.Format("Invalid request body."));
                builder.EndScope();
                if (!param.IsNullableBodyParameter())
                {
                    builder.AppendLine($"if ({pVar} is null)");
                    builder.BeginScope();
                    AppendBindingFailure(builder, hasFilter, NewBindingError("MissingBody", "Body", param.Name), CSharpLiteral.Format("Request body is required."));
                    builder.EndScope();
                }

                if (!param.SkipValidation)
                {
                    builder.AppendLine($"var requestValidator{index} = {GetService}<{RequestValidatorType}>(services) ?? new {DefaultRequestValidatorType}();");
                    builder.AppendLine($"if ({pVar} is not null && !requestValidator{index}.Validate({pVar}))");
                    builder.BeginScope();
                    // 失敗時のみ詳細を収集し直す（成功パスにアロケーションを増やさない）
                    // Details are collected only on failure, keeping the success path allocation free
                    builder.AppendLine($"var {pVar}errors = new global::System.Collections.Generic.List<global::System.ComponentModel.DataAnnotations.ValidationResult>();");
                    builder.AppendLine($"_ = requestValidator{index}.Validate({pVar}, {pVar}errors);");
                    builder.AppendLine($"var {pVar}message = {CSharpLiteral.Format("Validation failed: " + param.Name)} + ({pVar}errors.Count > 0 ? \": \" + global::System.String.Join(\"; \", {pVar}errors) : \"\");");
                    AppendBindingFailure(builder, hasFilter, NewBindingError("ValidationFailed", "Body", param.Name, $"{pVar}errors"), $"{pVar}message");
                    builder.EndScope();
                }

                builder.NewLine();
                return;
            case ParameterBindingType.FromQuery:
                BuildScalarOrArrayBinding(builder, param, index, hasFilter, "req.Query");
                return;
            case ParameterBindingType.FromRoute:
                BuildRouteBinding(builder, param, index, hasFilter);
                return;
            case ParameterBindingType.FromHeader:
                BuildHeaderBinding(builder, param, index, hasFilter);
                return;
            case ParameterBindingType.FromCookie:
                BuildCookieBinding(builder, param, index, hasFilter);
                return;
        }
    }

    // クエリ文字列またはヘッダー辞書から値を取り出し、スカラー / 配列 / Nullable のいずれかに変換するコードを出力する。
    // 変換失敗時は失敗の応答を返す (hasFilter の場合は ctx.Result にセットして return)。
    // Emits code to extract a value from a query/header dictionary and convert it to scalar, array, or Nullable.
    // On conversion failure, returns the binding failure response (or sets ctx.Result and returns when hasFilter is true).
    private static void BuildScalarOrArrayBinding(SourceBuilder builder, ParameterModel param, int index, bool hasFilter, string dictExpr)
    {
        var pVar = $"p{index}";
        var pRaw = $"p{index}raw";
        var typeName = param.Type.FullName;
        var key = param.Key;
        var defaultLiteral = param.HasDefault ? (param.DefaultValueLiteral ?? "default") : null;

        if (param.Type.IsArray && (param.Type.ElementType is not null))
        {
            var elemType = param.Type.ElementType.FullName;
            builder.AppendLine($"var {pVar} = global::System.Array.Empty<{elemType}>();");
            builder.AppendLine($"if ({dictExpr}.TryGetValue({CSharpLiteral.Format(key)}, out var {pRaw}) &&");
            builder.AppendLine($"    {pRaw} != global::Microsoft.Extensions.Primitives.StringValues.Empty)");
            builder.BeginScope();
            BuildArrayElementBinding(builder, param, param.Type.ElementType, index, hasFilter, $"{pRaw}.ToString()");
